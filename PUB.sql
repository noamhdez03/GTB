CREATE TABLE LOCALIDAD (
    COD_LOCALIDAD INT,
    NOMBRE VARCHAR(100) NOT NULL,
    PRIMARY KEY (COD_LOCALIDAD)
);

CREATE TABLE PUB (
    COD_PUB VARCHAR(20),
    NOMBRE VARCHAR(100) NOT NULL,
    LICENCIA_FISCAL VARCHAR(50) NOT NULL,
    DOMICILIO VARCHAR(255) NULL,
    FECHA_APERTURA DATE NOT NULL,
    HORARIO VARCHAR(4) NOT NULL,
    COD_LOCALIDAD INT NOT NULL,
    PRIMARY KEY (COD_PUB),
    FOREIGN KEY (COD_LOCALIDAD) REFERENCES LOCALIDAD(COD_LOCALIDAD) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT CHK_PUB_HORARIO CHECK (HORARIO IN ('HOR1', 'HOR2', 'HOR3'))
);

CREATE TABLE TITULAR (
    DNI_TITULAR VARCHAR(20),
    NOMBRE VARCHAR(100) NOT NULL,
    DOMICILIO VARCHAR(255) NULL,
    COD_PUB VARCHAR(20) NOT NULL,
    PRIMARY KEY (DNI_TITULAR),
    FOREIGN KEY (COD_PUB) REFERENCES PUB(COD_PUB) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE EMPLEADO (
    DNI_EMPLEADO VARCHAR(20),
    NOMBRE VARCHAR(100) NOT NULL,
    DOMICILIO VARCHAR(255) NULL,
    PRIMARY KEY (DNI_EMPLEADO)
);

CREATE TABLE EXISTENCIAS (
    COD_ARTICULO VARCHAR(20),
    NOMBRE VARCHAR(100) NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIO DECIMAL(10, 2) NOT NULL,
    COD_PUB VARCHAR(20) NOT NULL,
    PRIMARY KEY (COD_ARTICULO),
    FOREIGN KEY (COD_PUB) REFERENCES PUB(COD_PUB) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT CHK_EXISTENCIAS_PRECIO CHECK (PRECIO > 0)
);

CREATE TABLE PUB_EMPLEADO (
    COD_PUB VARCHAR(20),
    DNI_EMPLEADO VARCHAR(20),
    FUNCION VARCHAR(20) NOT NULL,
    PRIMARY KEY (COD_PUB, DNI_EMPLEADO, FUNCION),
    FOREIGN KEY (COD_PUB) REFERENCES PUB(COD_PUB) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (DNI_EMPLEADO) REFERENCES EMPLEADO(DNI_EMPLEADO) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CHK_PUB_EMP_FUNCION CHECK (FUNCION IN ('CAMARERO', 'SEGURIDAD', 'LIMPIEZA'))
);
